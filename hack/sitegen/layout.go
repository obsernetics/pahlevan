// The generated pages have to be indistinguishable from the two hand-written
// ones. A documentation page that arrives with its own header, its own
// typography and no way back to the site reads as a different website that
// happens to share a domain, and the reader stops trusting that the two are
// describing the same thing.
//
// So the header, nav and footer below are copies of pages/index.html's, with
// the link targets adjusted for the pages/docs/ subdirectory, and the pages
// load the same stylesheet rather than one of their own.

// siteURL is the published root. Only used for canonical and social metadata,
// which have to be absolute.
const siteURL = "https://obsernetics.github.io/pahlevan/"

// assetVersion is the cache-busting suffix on the stylesheet and script.
//
// It is a constant here and a literal in the two hand-written pages, and the
// three have to move together: a returning visitor holding a cached main.css
// from before the documentation rules existed would get an unstyled wall of
// text, and would have no reason to hard-refresh.
const assetVersion = "6"

// Layout is everything the shared chrome needs to know about one page.
type Layout struct {
	// Title is the <title>, without the "Pahlevan - " prefix.
	Title string
	// Description is the meta description and the social card text.
	Description string
	// Canonical is the page's path below siteURL, e.g. "docs/architecture.html".
	Canonical string
	// Source names the file this page was generated from, so a reader who
	// views source, or an editor who opens the wrong file, is told where the
	// content actually lives.
	Source string
	// Body is the <main> content. It is generated markup, not user input.
	Body string
	// DocsIsCurrent marks the Docs nav link with aria-current.
	DocsIsCurrent bool
}

