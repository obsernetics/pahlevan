// newLayout escapes everything that lands in an attribute or in text.
//
// The title and description come out of a markdown file anybody can edit. An
// unescaped quote in a heading would close the content attribute of a meta tag
// and put the rest of the sentence into the markup.
func newLayout(title, description, canonical, source, body string) Layout {
	return Layout{
		Title:       html.EscapeString(title),
		Description: html.EscapeString(description),
		Canonical:   html.EscapeString(canonical),
		Source:      html.EscapeString(source),
		Body:        body,
	}
}

// render wraps a body in the site chrome.
func (l Layout) render() ([]byte, error) {
	var buf bytes.Buffer
	if err := pageTemplate.Execute(&buf, l); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
