func TestBuildRosterResolvesTheWorkloadExactly(t *testing.T) {
	// The usual shortcut is to strip the hash off a ReplicaSet's name, which
	// is wrong for a Deployment whose own name ends in something hash-shaped.
	// One list per kind resolves it instead.
	fc, _ := installFakeClients(t,
		netpolPod("prod", "web-abc-1", "10.0.0.1", "web-abc", map[string]string{"app": "web"}),
		netpolReplicaSet("prod", "web-abc", "web-7f4d"),
		netpolPod("prod", "solo", "10.0.0.9", "", nil),
	)

	roster, err := buildRoster(context.Background(), fc, nil)
	require.NoError(t, err)
	require.Len(t, roster, 2)

	byName := map[string]netpol.Pod{}
	for _, p := range roster {
		byName[p.Name] = p
	}
	assert.Equal(t, "Deployment/web-7f4d", byName["web-abc-1"].Workload)
	assert.Empty(t, byName["solo"].Workload, "a pod with no controller is not part of a workload")
}

