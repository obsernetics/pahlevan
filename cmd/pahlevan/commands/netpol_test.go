func TestFoldProfilesJoinsTheContainersOfOneWorkload(t *testing.T) {
	// Containers of a pod share its network namespace, so their learned
	// destinations are one workload's traffic and not several.
	fc, _ := installFakeClients(t,
		netpolProfile("prod", "a", "web-1", "Deployment", "web", "10.0.1.1:8080"),
		netpolProfile("prod", "b", "web-1", "Deployment", "web", "10.0.1.1:8080", "10.0.1.1:53"),
		netpolProfile("prod", "c", "web-2", "Deployment", "web", "10.0.2.2:443"),
	)
	var list policyv1alpha1.ContainerProfileList
	require.NoError(t, fc.List(context.Background(), &list))

	obs := foldProfiles(context.Background(), fc, list.Items)
	require.Len(t, obs, 1)
	assert.Equal(t, "Deployment/web", obs[0].Workload)
	assert.Equal(t, []string{"web-1", "web-2"}, obs[0].Pods)
	assert.Len(t, obs[0].Destinations, 3, "the same destination seen twice is one destination")
	assert.Equal(t, "10.0.1.1", obs[0].Destinations[0].IP, "destinations are sorted so a rerun is not a diff")
}

