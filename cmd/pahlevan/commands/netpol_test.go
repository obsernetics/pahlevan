func TestWindowLookupReadsThePolicyAndTheSchedule(t *testing.T) {
	yes := true
	pol := &policyv1alpha1.PahlevanPolicy{
		ObjectMeta: metav1.ObjectMeta{Namespace: "prod", Name: "nightly"},
		Spec: policyv1alpha1.PahlevanPolicySpec{
			LearningConfig: policyv1alpha1.LearningConfig{
				Duration: &metav1.Duration{Duration: 50 * time.Minute},
			},
		},
	}
	cron := &batchv1.CronJob{
		ObjectMeta: metav1.ObjectMeta{Namespace: "prod", Name: "backup"},
		Spec:       batchv1.CronJobSpec{Schedule: "0 3 * * *"},
	}
	job := &batchv1.Job{ObjectMeta: metav1.ObjectMeta{
		Namespace: "prod", Name: "backup-1",
		OwnerReferences: []metav1.OwnerReference{{
			APIVersion: "batch/v1", Kind: "CronJob", Name: "backup", Controller: &yes,
		}},
	}}
	pod := &corev1.Pod{ObjectMeta: metav1.ObjectMeta{
		Namespace: "prod", Name: "backup-1-xyz",
		OwnerReferences: []metav1.OwnerReference{{
			APIVersion: "batch/v1", Kind: "Job", Name: "backup-1", Controller: &yes,
		}},
	}}
	fc, _ := installFakeClients(t, pol, cron, job, pod)

	profile := netpolProfile("prod", "p", "backup-1-xyz", "CronJob", "backup")
	profile.Spec.PolicyRef = "nightly"

	w := newWindowLookup(fc)
	window, schedule := w.for_(context.Background(), profile)
	assert.Equal(t, 50*time.Minute, window)
	assert.Equal(t, "0 3 * * *", schedule, "the schedule is two hops above the pod and is never on it")

	// Cached: a second ask must not re-read the policy.
	require.NoError(t, fc.Delete(context.Background(), pol))
	again, _ := w.for_(context.Background(), profile)
	assert.Equal(t, 50*time.Minute, again)
}

