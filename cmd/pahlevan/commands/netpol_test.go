func TestParseDestination(t *testing.T) {
	d, ok := parseDestination(" 10.0.0.1:5432 ")
	require.True(t, ok)
	assert.Equal(t, "10.0.0.1", d.IP)
	assert.Equal(t, int32(5432), d.Port)
	assert.Equal(t, corev1.ProtocolTCP, d.Protocol)

	d, ok = parseDestination("[2001:db8::1]:443")
	require.True(t, ok)
	assert.Equal(t, "2001:db8::1", d.IP)

	for _, bad := range []string{"", "10.0.0.1", "10.0.0.1:0", "10.0.0.1:http", "postgres:5432", "10.0.0.1:99999"} {
		_, ok := parseDestination(bad)
		assert.False(t, ok, "a malformed entry that became a rule would be a rule nobody can trace: %q", bad)
	}
}

