// A namespace with two workloads whose labels tell them apart, one learned
// baseline, and the pods to check any generated selector against.

func netpolPod(ns, name, ip, owner string, labels map[string]string) *corev1.Pod {
	p := &corev1.Pod{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: name, Labels: labels},
		Status:     corev1.PodStatus{PodIP: ip},
	}
	if owner != "" {
		yes := true
		p.OwnerReferences = []metav1.OwnerReference{{
			APIVersion: "apps/v1", Kind: "ReplicaSet", Name: owner, Controller: &yes,
		}}
	}
	return p
}

func netpolReplicaSet(ns, name, deployment string) *appsv1.ReplicaSet {
	yes := true
	return &appsv1.ReplicaSet{ObjectMeta: metav1.ObjectMeta{
		Namespace: ns, Name: name,
		OwnerReferences: []metav1.OwnerReference{{
			APIVersion: "apps/v1", Kind: "Deployment", Name: deployment, Controller: &yes,
		}},
	}}
}

func netpolProfile(ns, name, pod, kind, workload string, dests ...string) *policyv1alpha1.ContainerProfile {
	return &policyv1alpha1.ContainerProfile{
		ObjectMeta: metav1.ObjectMeta{Namespace: ns, Name: name},
		Spec: policyv1alpha1.ContainerProfileSpec{
			Namespace: ns,
			PodName:   pod,
			Workload:  &policyv1alpha1.WorkloadReference{Kind: kind, Name: workload, Namespace: ns},
		},
		Status: policyv1alpha1.ContainerProfileStatus{
			Phase:                      "Enforcing",
			LearnedNetworkDestinations: dests,
		},
	}
}

// netpolCluster is one web Deployment talking to one api Deployment.
func netpolCluster() []crclient.Object {
	return []crclient.Object{
		netpolPod("prod", "web-abc-1", "10.0.0.1", "web-abc", map[string]string{"app": "web"}),
		netpolPod("prod", "api-def-1", "10.0.1.1", "api-def", map[string]string{"app": "api"}),
		netpolReplicaSet("prod", "web-abc", "web"),
		netpolReplicaSet("prod", "api-def", "api"),
		netpolProfile("prod", "web-abc-1-main", "web-abc-1", "Deployment", "web", "10.0.1.1:8080", "10.0.1.1:53"),
	}
}

func runNetpol(t *testing.T, args ...string) (string, error) {
	t.Helper()
	cmd := NewNetpolCommand()
	var out bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&out)
	cmd.SetArgs(args)
	err := cmd.Execute()
	return out.String(), err
}

