// Package-level counters, registered exactly once (in init) with the
// controller-runtime metrics registry - which is what the agent's metrics server
// actually exposes on :8080/metrics. (The previous code registered per-Manager on
// the DEFAULT registry, which both panicked on a second Manager AND meant the
// pahlevan_* metrics never appeared on the served endpoint.)
//
// These describe the eBPF data plane: what the ring-buffer reader decoded and
// what the kernel denied. They are deliberately named pahlevan_ebpf_* and keyed
// only by event kind. The richer, container-attributed series live in
// pkg/metrics and belong to the policy plane; keeping the two apart avoids two
// packages registering the same metric name with different label dimensions,
// which Prometheus rejects.
const (
	kindSyscall    = "syscall"
	kindNetwork    = "network"
	kindFile       = "file"
	kindExec       = "exec"
	kindCapability = "capability"
)

var eventKinds = []string{kindSyscall, kindNetwork, kindFile, kindExec, kindCapability}

var (
	ebpfEventsTotal = prometheus.NewCounterVec(prometheus.CounterOpts{
		Name: "pahlevan_ebpf_events_total",
		Help: "eBPF events decoded from the ring buffers, by event kind",
	}, []string{"kind"})
	ebpfDenialsTotal = prometheus.NewCounterVec(prometheus.CounterOpts{
		Name: "pahlevan_ebpf_denials_total",
		Help: "Operations denied in-kernel with EPERM, by event kind",
	}, []string{"kind"})
	ebpfDecodeErrorsTotal = prometheus.NewCounterVec(prometheus.CounterOpts{
		Name: "pahlevan_ebpf_decode_errors_total",
		Help: "Ring-buffer records that could not be decoded, by event kind",
	}, []string{"kind"})
)

func init() {
	ctrlmetrics.Registry.MustRegister(
		ebpfEventsTotal, ebpfDenialsTotal, ebpfDecodeErrorsTotal,
	)
	// Pre-create every child so a kind that has not fired yet reports 0 rather
	// than being absent. An absent series and a genuinely idle one look the same
	// on a dashboard, which is exactly the ambiguity an operator cannot afford
	// when the question is "is enforcement working?".
	for _, k := range eventKinds {
		ebpfEventsTotal.WithLabelValues(k)
		ebpfDenialsTotal.WithLabelValues(k)
		ebpfDecodeErrorsTotal.WithLabelValues(k)
	}
}

// dataPlaneCounters holds the per-kind children resolved once, so the hot path
// does not pay for a label lookup on every event.
type dataPlaneCounters struct {
	events, denials, decodeErrors prometheus.Counter
}

func newDataPlaneCounters(kind string) dataPlaneCounters {
	return dataPlaneCounters{
		events:       ebpfEventsTotal.WithLabelValues(kind),
		denials:      ebpfDenialsTotal.WithLabelValues(kind),
		decodeErrors: ebpfDecodeErrorsTotal.WithLabelValues(kind),
	}
}

