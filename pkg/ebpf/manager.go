// EventReader interface for reading events from eBPF programs
type EventReader interface {
	Read() (*EventRecord, error)
}

// EventRecord represents a raw event record from eBPF
type EventRecord struct {
	RawSample []byte
}

// processEvents handles event processing for different event types
func (m *Manager) processEvents(ctx context.Context, eventType string) {
	for {
		select {
		case <-ctx.Done():
			return
		case <-m.stopCh:
			return
		default:
			var rawSample []byte
			var err error

			switch eventType {
			case "syscall":
				if m.eventReader == nil {
					return
				}
				record, e := m.eventReader.Read()
				if e != nil {
					continue
				}
				rawSample = record.RawSample
				err = e
			case "network":
				if m.networkEventReader == nil {
					return
				}
				record, e := m.networkEventReader.Read()
				if e != nil {
					continue
				}
				rawSample = record.RawSample
				err = e
			case "file":
				if m.fileEventReader == nil {
					return
				}
				record, e := m.fileEventReader.Read()
				if e != nil {
					continue
				}
				rawSample = record.RawSample
				err = e
			case "capability":
				if m.capEventReader == nil {
					return
				}
				record, e := m.capEventReader.Read()
				if e != nil {
					continue
				}
				rawSample = record.RawSample
				err = e
			case "exec":
				if m.execEventReader == nil {
					return
				}
				record, e := m.execEventReader.Read()
				if e != nil {
					continue
				}
				rawSample = record.RawSample
				err = e
			default:
				return
			}

			if err != nil {
				continue
			}

			m.handleEventRecord(ctx, eventType, rawSample)
		}
	}
}

// handleEventRecord processes a single event record based on type.
//
// Every kind now counts its events, its denials, and its decode failures
// uniformly. Previously exec and capability records were counted only when
// denied, so an agent seeing exec traffic but denying none reported nothing at
// all, and undecodable records were dropped in complete silence.
func (m *Manager) handleEventRecord(ctx context.Context, eventType string, rawSample []byte) {
	switch eventType {
	case kindSyscall:
		event := parseSyscallEvent(rawSample)
		if event == nil {
			m.counters[kindSyscall].decodeErrors.Inc()
			return
		}
		m.counters[kindSyscall].events.Inc()
		if m.otelSyscallCounter != nil {
			m.otelSyscallCounter.Add(ctx, 1)
		}
		m.notifyHandlers(func(h EventHandler) { _ = h.HandleSyscallEvent(event) })
	case kindNetwork:
		event := parseNetworkEvent(rawSample)
		if event == nil {
			m.counters[kindNetwork].decodeErrors.Inc()
			return
		}
		m.counters[kindNetwork].events.Inc()
		if m.otelNetworkCounter != nil {
			m.otelNetworkCounter.Add(ctx, 1)
		}
		// Direction bit 0x80 marks an in-kernel denied connect (see network_monitor.c).
		if event.Direction&DeniedDirection != 0 {
			m.counters[kindNetwork].denials.Inc()
		}
		m.notifyHandlers(func(h EventHandler) { _ = h.HandleNetworkEvent(event) })
	case kindFile:
		event := parseFileEvent(rawSample)
		if event == nil {
			m.counters[kindFile].decodeErrors.Inc()
			return
		}
		m.counters[kindFile].events.Inc()
		if m.otelFileCounter != nil {
			m.otelFileCounter.Add(ctx, 1)
		}
		// Flag bit 0x80000000 marks an in-kernel denied open (see file_monitor.c).
		if event.Flags&DeniedFlag != 0 {
			m.counters[kindFile].denials.Inc()
		}
		m.notifyHandlers(func(h EventHandler) { _ = h.HandleFileEvent(event) })
	case kindCapability:
		event := parseCapabilityEvent(rawSample)
		if event == nil {
			m.counters[kindCapability].decodeErrors.Inc()
			return
		}
		m.counters[kindCapability].events.Inc()
		if event.Flags&DeniedFlag != 0 {
			m.counters[kindCapability].denials.Inc()
		}
		m.notifyHandlers(func(h EventHandler) { _ = h.HandleCapabilityEvent(event) })
	case kindExec:
		event := parseProcessEvent(rawSample)
		if event == nil {
			m.counters[kindExec].decodeErrors.Inc()
			return
		}
		m.counters[kindExec].events.Inc()
		// Flag bit 0x80000000 marks an in-kernel denied execve (see exec_monitor.c).
		if event.Flags&DeniedFlag != 0 {
			m.counters[kindExec].denials.Inc()
		}
		m.notifyHandlers(func(h EventHandler) { _ = h.HandleProcessEvent(event) })
	}
}

// notifyHandlers safely notifies all event handlers
func (m *Manager) notifyHandlers(notify func(EventHandler)) {
	m.mu.RLock()
	handlers := make([]EventHandler, len(m.eventHandlers))
	copy(handlers, m.eventHandlers)
	m.mu.RUnlock()

	// Dispatch synchronously. This used to spawn a goroutine per handler per
	// event, which cost a scheduler round-trip and an allocation on every
	// record - the dominant cost in the pipeline at any real event rate - and
	// delivered events out of order, so a handler could observe an exec after
	// the profile it belonged to had already been reconciled.
	//
	// The tradeoff is that a slow handler now stalls the ring-buffer reader.
	// That is the correct place for the decision: handlers that can block own a
	// bounded queue and drop under pressure (see pkg/export.NewQueue), which
	// makes the loss explicit and countable instead of silently unbounding
	// memory in a goroutine pile-up.
	for _, handler := range handlers {
		notify(handler)
	}
}

